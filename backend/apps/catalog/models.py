from django.contrib.postgres.indexes import GinIndex
from django.contrib.postgres.search import SearchVectorField
from django.db import models

from .enrichment import category_group, category_label

MONEY = {"max_digits": 12, "decimal_places": 2}


class Category(models.Model):
    name = models.CharField(max_length=100, unique=True, help_text="Olist (Portuguese) name")
    name_english = models.CharField(max_length=100)
    slug = models.SlugField(max_length=100, unique=True)

    class Meta:
        ordering = ["name_english"]
        verbose_name_plural = "categories"

    def __str__(self) -> str:
        return self.label

    @property
    def label(self) -> str:
        return category_label(self.name_english)

    @property
    def group(self) -> str:
        return category_group(self.name_english)


class Seller(models.Model):
    external_id = models.CharField(max_length=32, unique=True)
    zip_code_prefix = models.CharField(max_length=5)
    city = models.CharField(max_length=100)
    state = models.CharField(max_length=2, db_index=True)

    def __str__(self) -> str:
        return f"{self.external_id[:8]} ({self.city}/{self.state})"


class Product(models.Model):
    external_id = models.CharField(max_length=32, unique=True)
    category = models.ForeignKey(
        Category, null=True, blank=True, on_delete=models.SET_NULL, related_name="products"
    )
    # Generated by apps.catalog.enrichment (Olist has no names or descriptions)
    name = models.CharField(max_length=200)
    slug = models.SlugField(max_length=220, unique=True)
    description = models.TextField(blank=True)
    image_url = models.URLField(null=True, blank=True)

    name_length = models.PositiveIntegerField(null=True, blank=True)
    description_length = models.PositiveIntegerField(null=True, blank=True)
    photos_qty = models.PositiveSmallIntegerField(null=True, blank=True)
    weight_g = models.PositiveIntegerField(null=True, blank=True)
    length_cm = models.PositiveIntegerField(null=True, blank=True)
    height_cm = models.PositiveIntegerField(null=True, blank=True)
    width_cm = models.PositiveIntegerField(null=True, blank=True)

    # Denormalised stats, refreshed by apps.catalog.stats.refresh_product_stats
    min_price = models.DecimalField(
        **MONEY, null=True, blank=True, help_text="Lowest price among in-stock offers"
    )
    rating_avg = models.DecimalField(max_digits=3, decimal_places=2, null=True, blank=True)
    rating_count = models.PositiveIntegerField(default=0)
    sales_count = models.PositiveIntegerField(default=0)
    first_sold_at = models.DateTimeField(null=True, blank=True)
    search_vector = SearchVectorField(null=True, editable=False)

    class Meta:
        indexes = [
            GinIndex(fields=["search_vector"], name="product_search_gin"),
            models.Index(fields=["sales_count"], name="product_sales_idx"),
            models.Index(fields=["min_price"], name="product_min_price_idx"),
            models.Index(fields=["rating_avg"], name="product_rating_idx"),
            models.Index(fields=["first_sold_at"], name="product_first_sold_idx"),
        ]

    def __str__(self) -> str:
        return self.name or self.external_id


class Offer(models.Model):
    """One seller selling one product. Derived from Olist order items at import."""

    product = models.ForeignKey(Product, on_delete=models.CASCADE, related_name="offers")
    seller = models.ForeignKey(Seller, on_delete=models.PROTECT, related_name="offers")
    price = models.DecimalField(**MONEY, help_text="Median Olist item price for this pair")
    stock = models.PositiveIntegerField()

    class Meta:
        ordering = ["price"]
        constraints = [
            models.UniqueConstraint(fields=["product", "seller"], name="uniq_offer_product_seller")
        ]
        indexes = [models.Index(fields=["product", "price"], name="offer_product_price_idx")]

    def __str__(self) -> str:
        return f"{self.product} by {self.seller} @ {self.price}"

    @property
    def in_stock(self) -> bool:
        return self.stock > 0
